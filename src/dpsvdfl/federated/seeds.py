"""Seed plan of one experimental replicate (paired design of the paper, Sec. V-D).

One experiment seed (0, 1 or 2 in the paper) derives separate, data-independent streams:

* common to both variants of the method (adaptive and fixed-rank), so that they are matched in their inputs:
  classifier initialisation, client partition, Poisson sampling schedule and local training
  (minibatch order, padding and data augmentation of every client in every round);
* specific to one variant: the Gaussian DP noise. The variant's *noise namespace* enters the derivation through a
  stable SHA-256 identifier, so two variants with the same experiment seed draw independent noise.

Per-round and per-client seeds are pure functions of (stream seed, round index, slot ID): the seed of client ``i`` in
round ``t`` never depends on iteration order. Round indices are zero-based (round t = 1 has round_index 0).

In ``benchmark_reproducible`` mode these seeds are public and reconstructible, hence the sampled sets and the noise can
be regenerated by anyone: such a run is NOT an operationally private release (see ``dpsvdfl.privacy.modes``).
"""

import re
from dataclasses import dataclass

from dpsvdfl.reproducibility import derive_indexed_seed, stable_namespace_id

# DP-noise namespaces of the variants reported in the paper (the strings are part of the seed derivation: changing
# one changes every noise draw of that variant).
DPSVDFL_NOISE_NAMESPACE = "dp-svd-fl"  # adaptive DP-SVD-FL
FIXED_SPECTRAL_NOISE_NAMESPACE = "fixed-spectral"  # fixed-rank spectral ablation

# Optional noise context of a separately released run inside a sweep. The privacy sweep of the paper used
# "e9:sigma<1000 sigma>", e.g. "dp-svd-fl|e9:sigma0788". It enters ONLY the DP-noise derivation: the common streams
# (partition, sampling, local training, initialisation) are unchanged.
NOISE_CONTEXT_SEPARATOR = "|"
PRIVACY_SWEEP_CONTEXT_PREFIX = "e9:"
_NOISE_CONTEXT_PATTERN = re.compile(r"[A-Za-z0-9_.:=-]+")

# Stream identifiers (stable: changing one changes every derived seed).
_CLASSIFIER_STREAM = 0
_PARTITION_STREAM = 1
_SAMPLING_STREAM = 2
_LOCAL_TRAINING_STREAM = 3
_NOISE_STREAM = 4


def check_noise_context(noise_context) -> str:
    """A noise context is a non-empty string of ``[A-Za-z0-9_.:=-]``; returns it unchanged."""
    if not isinstance(noise_context, str) or not _NOISE_CONTEXT_PATTERN.fullmatch(noise_context):
        raise ValueError(f"a noise context must be a non-empty string of [A-Za-z0-9_.:=-], got {noise_context!r}")
    return noise_context


def contextual_noise_namespace(namespace: str, noise_context: str | None) -> str:
    """``namespace`` without a context, otherwise ``"<namespace>|<context>"``."""
    if noise_context is None:
        return namespace
    return f"{namespace}{NOISE_CONTEXT_SEPARATOR}{check_noise_context(noise_context)}"


def privacy_sweep_noise_context(noise_multiplier: float) -> str:
    """The noise context of one sigma level of the privacy sweep, e.g. 0.788 -> ``"e9:sigma0788"``."""
    code = round(noise_multiplier * 1000)
    if noise_multiplier <= 0 or abs(code - noise_multiplier * 1000) > 1e-6:
        raise ValueError(f"the privacy sweep encodes 1000 sigma: sigma must be a positive multiple of 0.001, "
                         f"got {noise_multiplier}")
    return f"{PRIVACY_SWEEP_CONTEXT_PREFIX}sigma{int(code):04d}"


@dataclass(frozen=True)
class RunSeedPlan:
    """Derived seeds of one replicate for one variant. INTERNAL: never publish them with a private release."""

    experiment_seed: int
    method_noise_namespace: str
    classifier_seed: int
    partition_seed: int
    sampling_seed: int
    local_training_master_seed: int
    noise_master_seed: int

    @classmethod
    def create(cls, experiment_seed: int, method_noise_namespace: str = DPSVDFL_NOISE_NAMESPACE) -> "RunSeedPlan":
        return cls(
            experiment_seed=experiment_seed,
            method_noise_namespace=method_noise_namespace,
            classifier_seed=derive_indexed_seed(experiment_seed, _CLASSIFIER_STREAM),
            partition_seed=derive_indexed_seed(experiment_seed, _PARTITION_STREAM),
            sampling_seed=derive_indexed_seed(experiment_seed, _SAMPLING_STREAM),
            local_training_master_seed=derive_indexed_seed(experiment_seed, _LOCAL_TRAINING_STREAM),
            noise_master_seed=derive_indexed_seed(
                experiment_seed, _NOISE_STREAM, stable_namespace_id(method_noise_namespace)
            ),
        )

    def local_training_seed(self, round_index: int, slot_id: int) -> int:
        """Training seed of client slot ``slot_id`` in round ``round_index`` (common to both variants)."""
        return derive_indexed_seed(self.local_training_master_seed, round_index, slot_id)

    def noise_seed(self, round_index: int) -> int:
        """Gaussian-noise seed of round ``round_index`` for this variant (fresh in every round)."""
        return derive_indexed_seed(self.noise_master_seed, round_index)

    def common_streams(self) -> tuple[int, int, int, int]:
        """(classifier, partition, sampling, local-training) seeds shared by both variants."""
        return self.classifier_seed, self.partition_seed, self.sampling_seed, self.local_training_master_seed
